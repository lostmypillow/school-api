WITH RES AS (
    SELECT
        ID,
        SOURCE,
        STUDENT_ID,
        STUDENT_NAME,
        MIDDLE_SCHOOL_NAME,
        MIDDLE_SCHOOL_CLASS,
        HIGH_SCHOOL_NAME,
        HIGH_SCHOOL_CLASS,
        REGISTERED_CLASS,
        TRIAL_DATE,
        TELEPHONE,
        MOBILE,
        NOTES,
        PARENT_NAME,
        MANAGER,
        STATUS,
        CURRENT_GRADE,
        CREATED_AT,
        UPDATED_AT,
        row_number() OVER (ORDER BY CREATED_AT DESC) AS ROW_NUM,
        count(*) OVER () AS TOTAL_COUNT
    FROM TRIAL_RECORDS
)

SELECT
    ID,
    SOURCE,
    STUDENT_ID,
    STUDENT_NAME,
    MIDDLE_SCHOOL_NAME,
    MIDDLE_SCHOOL_CLASS,
    HIGH_SCHOOL_NAME,
    HIGH_SCHOOL_CLASS,
    REGISTERED_CLASS,
    TRIAL_DATE,
    TELEPHONE,
    MOBILE,
    NOTES,
    PARENT_NAME,
    MANAGER,
    STATUS,
    CURRENT_GRADE,
    CREATED_AT,
    UPDATED_AT,
    TOTAL_COUNT
FROM RES
WHERE ROW_NUM > $1 AND ROW_NUM <= ($2 + $2)
ORDER BY CREATED_AT DESC;
